CREATE TRIGGER trg_auto_fed_dispatch_entity_relationships
AFTER INSERT OR UPDATE OR DELETE ON entity_relationships
FOR EACH ROW EXECUTE FUNCTION auto_fed_dispatch_entity_relationships();

-- company_custom_field_values is high-traffic/all-companies -- keep this
-- dispatch as cheap as possible for every write that isn't a watched field.
CREATE OR REPLACE FUNCTION auto_fed_dispatch_custom_field_values() RETURNS trigger AS $$
DECLARE
  v_row company_custom_field_values := COALESCE(NEW, OLD);
  v_field company_custom_fields;
  v_registry_id uuid;
BEGIN
  SELECT * INTO v_field FROM company_custom_fields WHERE id = v_row.field_id;
  IF NOT FOUND THEN RETURN v_row; END IF;
  FOR v_registry_id IN
    SELECT id FROM auto_fed_registries WHERE source_table_name = v_field.table_name AND company_id = v_field.company_id AND is_active
  LOOP
    PERFORM auto_fed_recompute(v_registry_id, v_row.record_id);
  END LOOP;
  RETURN v_row;
END;
$$ LANGUAGE plpgsql;

