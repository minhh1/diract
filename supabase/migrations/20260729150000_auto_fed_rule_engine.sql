-- Generic, reusable "auto-fed" rule engine -- replaces the Niksen/entities-
-- specific niksen_recompute_entity_irregularities()/niksen_upsert_irregularity()
-- pair (see 20260729040000 and follow-ups) with a config-driven system any
-- future auto-populated registry table can plug into by inserting rows,
-- not writing new trigger functions.
--
-- auto_fed_registries: one row per "watched source -> target table" link
-- (e.g. watch entities, write violations into the Irregularities table).
-- auto_fed_rules: one row per rule within a registry -- condition_sql is a
-- boolean SQL expression evaluated with the watched row aliased `r`
-- (`SELECT (<condition_sql>) FROM <source_table_name> r WHERE r.id = $1`),
-- so a rule can reference joins/subqueries against any other table freely,
-- same as niksen's original rules did inline. This is trusted, developer-
-- authored config (inserted by migrations, not exposed to end users to type
-- freely), same trust level as any other migration SQL -- not a general
-- "let users write SQL" feature.
--
-- The target (auto-fed) table itself must follow a fixed field_key
-- convention: issue_type/classification/detail/status/detected_at/
-- source_table/target_field_key (all 'text' except detected_at 'date'),
-- plus one relation field whose field_type matches the source
-- (entity/project/property) linking each row back to what triggered it --
-- see auto_fed_upsert_item's resolution below. This is what lets the
-- engine work against ANY target table shaped this way, not just
-- Irregularities.

-- page_kind is the "different type of table" distinction requested --
-- orthogonal to base_table (which picks WHERE an item's data lives).
-- 'user_dependent' (default) = staff add/remove items and edit fields
-- freely, e.g. matters/entities boards. 'auto_fed' = items are entirely
-- system-generated by this rule engine -- no manual add, fields read-only
-- except whatever a registry's editable_field_keys allows (e.g. Status).
ALTER TABLE client_update_pages ADD COLUMN IF NOT EXISTS page_kind text NOT NULL DEFAULT 'user_dependent'
  CHECK (page_kind IN ('user_dependent', 'auto_fed'));

CREATE TABLE IF NOT EXISTS auto_fed_registries (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  company_id uuid NOT NULL REFERENCES companies(id) ON DELETE CASCADE,
  target_table_id uuid NOT NULL REFERENCES company_tables(id) ON DELETE CASCADE,
  source_table_name text NOT NULL,
  -- Source-table field_keys (native columns, or a company_custom_fields.id)
  -- that stay directly editable on the auto-fed board despite it otherwise
  -- being read-only-except-via-fix -- e.g. 'status', for ticking Open/
  -- Resolved by hand. See app/api/client-update-pages/[id]/values/route.ts.
  editable_field_keys text[] NOT NULL DEFAULT '{}',
  is_active boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (target_table_id)
);

CREATE TABLE IF NOT EXISTS auto_fed_rules (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  registry_id uuid NOT NULL REFERENCES auto_fed_registries(id) ON DELETE CASCADE,
  rule_key text NOT NULL,
  label text NOT NULL,
  classification text NOT NULL,
  detail text NOT NULL,
  -- Native column name on the source table, a company_custom_fields.id, or
  -- a source-specific sentinel (e.g. 'trust_link') -- see
  -- app/api/client-update-pages/[id]/items/[itemId]/fix/route.ts for how
  -- this resolves into an actual editable field.
  target_field_key text,
  condition_sql text NOT NULL,
  display_order integer NOT NULL DEFAULT 0,
  is_active boolean NOT NULL DEFAULT true,
  UNIQUE (registry_id, rule_key)
);

